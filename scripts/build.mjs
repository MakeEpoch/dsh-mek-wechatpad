/**
 * Bundle the browser half into the ModuleLoader format dsh loads.
 *
 * The shell already ships React (as `react` / `react/jsx-runtime` in its own
 * module registry), so those stay external; everything else in the client is
 * either a dsh service reached through `ctx` or plain DOM code.
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const packageRoot = fileURLToPath(new URL('../', import.meta.url));
const loaderId = process.env.DSH_WECHATPAD_CLIENT_ID ?? 'dsh-mek-wechatpad';

let esbuild;
try {
  esbuild = require('esbuild');
} catch {
  const fallback = process.env.DSH_ESBUILD_MODULE;
  if (!fallback) throw new Error('esbuild is missing; run npm install in the plugin directory');
  esbuild = require(fallback);
}

const result = await esbuild.build({
  absWorkingDir: packageRoot,
  entryPoints: ['client/index.js'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome100'],
  // dsh's module registry already ships React; these must stay external.
  external: ['@deepseek-ai/dsh-client-ui-primitives', 'react', 'react/jsx-runtime', 'react-dom', 'react-dom/client'],
  jsx: 'transform',
  legalComments: 'none',
  minify: process.env.NODE_ENV === 'production',
  logLevel: 'warning',
});

const bundled = result.outputFiles?.[0]?.text;
if (!bundled) throw new Error('esbuild produced no client bundle');

const wrapped = `// Generated by npm run build. dsh Client ModuleLoader bundle.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(loaderId)},
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${bundled}
    return module.exports;
  }
});
`;

await mkdir(new URL('../lib/', import.meta.url), { recursive: true });
await writeFile(new URL('../lib/client.js', import.meta.url), wrapped, 'utf8');
console.log(`Built dsh client: ${Buffer.byteLength(wrapped)} bytes -> lib/client.js`);
